const isAscii = (s) => /^[A-Za-z0-9&]+$/.test(s)
const escape = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')

// 英字だけの言葉は、別の単語の一部(例: RAPIDの中のAPI)に反応しないようにする
const MATCHERS = NEWS_NOTES.map((n) => ({
  note: n,
  re: new RegExp(
    n.keys.map((k) => (isAscii(k) ? `(?<![A-Za-z0-9])${escape(k)}(?![A-Za-z0-9])` : escape(k))).join('|'),
    'i',
  ),
}))

// 記事の文章に出てくる言葉の注を、最大 max 個まで返す
export function findNotes(text, max = 3) {
  const found = []
  for (const m of MATCHERS) {
    if (m.re.test(text)) found.push(m.note)
    if (found.length >= max) break
  }
  return found
}
